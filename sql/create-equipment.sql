CREATE TABLE IF NOT EXISTS public.equipment (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 seed_key text UNIQUE,
 category text NOT NULL CHECK (category IN ('exam','surgery','treatment')),
 title text NOT NULL CHECK (length(trim(title)) > 0),
 description text NOT NULL DEFAULT '',
 image_url text
);
ALTER TABLE public.equipment ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.equipment FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.equipment TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.equipment TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.equipment_id_seq TO authenticated;
DROP POLICY IF EXISTS equipment_public_read ON public.equipment;
CREATE POLICY equipment_public_read ON public.equipment FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS equipment_admin_write ON public.equipment;
CREATE POLICY equipment_admin_write ON public.equipment FOR ALL TO authenticated USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = (SELECT auth.uid()) AND role = 'admin')) WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = (SELECT auth.uid()) AND role = 'admin'));
